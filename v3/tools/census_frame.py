"""Census frame for the v3 re-test census: every speed claim in the analysis sample whose article links public code.

    python v3/tools/census_frame.py

Reads audit/coding/records/*.json (read-only). Selects records with included.stratum == "speed" and
reporting.code_available == "yes". Records already re-tested in v2 are listed but not re-run (ALREADY_RETESTED).
Writes v3/census/frame.json and v3/census/frame.md. Nothing outside v3/ is written.
"""
from __future__ import annotations

import json
import pathlib
import re

V3 = pathlib.Path(__file__).resolve().parents[1]
ROOT = V3.parent
OUT = V3 / "census"

# P00150 (Halle et al. 2021, the trained predictor) was attempted in v2 and stopped by its pre-registered
# reconstruction check (SMO v2 manuscript Sect. 2.6, Online Resource 5; evidence/p00150_check.json). It stays in the
# frame with that outcome and is not re-run. (Corrected 2026-09-25: the first version labelled it "HGTO"; HGTO is
# record P00512, outside the analysis sample.)
ALREADY_RETESTED = {"P00150": "attempted in v2; stopped at the reconstruction check (57 of 100 within 1 %, 95 required)"}


def verdict(rule) -> str:
    return rule.get("verdict") if isinstance(rule, dict) else str(rule)


def main():
    rows = []
    for f in sorted((ROOT / "audit" / "coding" / "records").glob("P*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        if (r.get("included") or {}).get("stratum") != "speed":
            continue
        if (r.get("reporting") or {}).get("code_available") != "yes":
            continue
        text = json.dumps(r, ensure_ascii=False)
        repos = sorted(set(m.rstrip(".") for m in re.findall(r"github\.com/[\w.-]+/[\w.-]+", text)))
        c, cl, b = r["citation"], r.get("claim") or {}, r.get("baseline") or {}
        rows.append({
            "pid": r["pid"],
            "title": c.get("title"),
            "year": c.get("year"),
            "doi": c.get("doi"),
            "status": ALREADY_RETESTED.get(r["pid"], "to re-test in v3"),
            "claim": cl.get("primary_outcome_paraphrase"),
            "claimed_speedup": cl.get("claimed_speedup"),
            "claimed_speedup_basis": cl.get("claimed_speedup_basis"),
            "classical_method": b.get("classical_method"),
            "implementation": b.get("implementation"),
            "solver": b.get("solver"),
            "hardware_classical": b.get("hardware_classical"),
            "hardware_ml": b.get("hardware_ml"),
            "problem_size": b.get("problem_size"),
            "data_available": (r.get("reporting") or {}).get("data_available"),
            "rules": {k: verdict(v) for k, v in (r.get("rules") or {}).items()},
            "repos": repos,
        })
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "frame.json").write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["# Census frame (generated by v3/tools/census_frame.py; do not edit)", "",
             f"Speed claims with public code in the analysis sample: {len(rows)}; to re-test in v3: "
             f"{sum(r['status'] == 'to re-test in v3' for r in rows)}.", "",
             "| PID | Year | Published factor | R1 | R2 | R3 | R4 | Data | Repository | Status |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ru = r["rules"]
        lines.append(f"| {r['pid']} | {r['year']} | {r['claimed_speedup']} | {ru.get('R1')} | {ru.get('R2')} | "
                     f"{ru.get('R3')} | {ru.get('R4')} | {r['data_available']} | {', '.join(r['repos'])} | "
                     f"{r['status']} |")
    (OUT / "frame.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
