"""Supplementary tables for the re-test, generated from evidence files (no hand-typed numbers).

    python -m analysis.supp_tables

S1  same-machine times per method and size: pinned loop-only (pre-registered benchmark measure), pinned with setup
    (per-design comparisons), and default-scheduling loop-only (sensitivity).
S2  compliance error and thresholded volume fraction per problem under OAT's evaluator.
S3  time to OAT's quality per problem (primary rule; GPU and CPU).
Writes manuscript/supplementary_tables.md.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def load(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def fmt(v, nd=3):
    return "—" if v is None else f"{v:.{nd}f}"


def main():
    pin = load("evidence/oat_retest_summary.json")["stages"]
    dflt = load("evidence/oat_retest_summary_default_sched.json")["stages"]
    ttq = load("evidence/ttq_summary.json")
    lines = ["# Supplementary tables (generated by `analysis/supp_tables.py`; do not edit by hand)", "",
             "## S1 Time per design on one RTX 5090 (medians over 5 NITO test problems; seconds)", "",
             "| Method | Size | Pinned, loop only | Pinned, with setup | Default scheduling, loop only |",
             "|---|---|---|---|---|"]
    stage_to_ttq = {"ours GPU 256": "256_gpu", "ours GPU 64": "64_gpu", "ours PARDISO 256": "256_pardiso",
                    "ours PARDISO 64": "64_pardiso"}
    for stage, s in pin.items():
        t = ttq.get(stage_to_ttq.get(stage, ""), {})
        label = " ".join(w for w in stage.split() if w not in ("64", "256"))
        lines.append(f"| {label} | {s['size']}² | {fmt(s['time_s_median'])} | "
                     f"{fmt(t.get('wall_150_incl_setup_median_s')) if t else 'setup not measured'} | "
                     f"{fmt(dflt.get(stage, {}).get('time_s_median'))} |")
    lines += ["", "OAT inference covers the sampling call per design (model loading and the data collator excluded). "
              "OAT's SIMP (pyEDGE) times cover the optimization loop only.", ""]
    lines += ["## S2 Compliance error (CE, %) and thresholded volume fraction under OAT's evaluator", "",
              "| Size | Problem | Target vf | OAT CE (vf) | Ours CE (vf) | OAT-SIMP CG CE |", "|---|---|---|---|---|---|"]
    for size in (256, 64):
        for e in load(f"evidence/oat_eval_n{size}.json"):
            c = e["candidates"]
            oat, ours, cg = c.get("OAT"), c.get("ours[gpu]"), c.get("OAT-SIMP[CG_OC]")
            lines.append(f"| {size}² | {e['problem_id']} | {e['vf_target']:.2f} | "
                         f"{oat['CE_pct']:+.2f} ({oat['vf_thresholded']:.3f}) | {ours['CE_pct']:+.2f} ({ours['vf_thresholded']:.3f}) | "
                         f"{'—' if cg is None else format(cg['CE_pct'], '+.2f')} |")
    lines += ["", "## S3 Time to OAT's quality (primary rule: CE at most OAT's, material at most max(target, OAT))", "",
              "| Size | Solver | Problem | OAT CE | Matched at K | Time with setup (s) | OAT time (s) |",
              "|---|---|---|---|---|---|---|"]
    inf = {s: {int(k): v["time_s"] for k, v in pin[f"OAT inference {s}"]["per_problem"].items()} for s in (256, 64)}
    for key in ("256_gpu", "256_pardiso", "64_gpu", "64_pardiso"):
        t = ttq.get(key)
        if not t:
            continue
        for p in t["per_problem"]:
            m = p["primary_ce_and_volume"]
            lines.append(f"| {t['size']}² | {t['solver']} | {p['problem_id']} | {p['CE_OAT_pct']:+.2f} | "
                         f"{m['matched_iters'] if m['matched'] else 'not matched'} | "
                         f"{fmt(m['matched_wall_incl_setup_s']) if m['matched'] else '—'} | {fmt(inf[t['size']][p['problem_id']])} |")
        r = t["rules"]["primary_ce_and_volume"]
        lines.append(f"| {t['size']}² | {t['solver']} | median ratio (ours/OAT, unmatched ranked slowest) | | | "
                     f"{fmt(r['ratio_median_censored'], 2) if r['ratio_median_censored'] is not None else 'undefined'} | |")
    (ROOT / "manuscript" / "supplementary_tables.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote manuscript/supplementary_tables.md")


if __name__ == "__main__":
    main()
